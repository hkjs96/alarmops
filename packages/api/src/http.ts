/**
 * Framework-agnostic request/response shapes for the console REST API (API-CONTRACT §2, §8).
 * A Next.js route handler (or any other adapter) builds an ApiRequest from the HTTP request + session and
 * writes the ApiResponse back. Nothing here imports a web framework or an auth provider.
 */
import { createHash } from 'node:crypto';
import type { AuthContext } from './auth.js';

export interface ApiRequest {
  method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
  /** Path below the API base, e.g. `/incidents/inc-1/ack` (a leading `/api/v1` is tolerated). */
  path: string;
  /** Single-valued query parameters. Empty strings are ignored (known-bugs 9-6). */
  query?: Record<string, string | undefined>;
  /** Header names are matched case-insensitively. */
  headers?: Record<string, string | undefined>;
  body?: unknown;
  /** Session principal resolved by the adapter; null = not signed in. */
  auth: AuthContext | null;
  /** Generated by the adapter per request; echoed in errors. */
  requestId: string;
}

export interface ApiResponse {
  status: number;
  headers: Record<string, string>;
  /** JSON-serialisable; undefined for 304. */
  body?: unknown;
}

const BASE_HEADERS = { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' } as const;

export const ok = (body: unknown, headers: Record<string, string> = {}, status = 200): ApiResponse => ({ status, headers: { ...BASE_HEADERS, ...headers }, body });

export class ApiError extends Error {
  constructor(readonly status: number, readonly code: string, message: string, readonly details: Record<string, unknown> = {}) {
    super(message);
  }
}

export function errorResponse(e: ApiError, requestId: string): ApiResponse {
  return { status: e.status, headers: { ...BASE_HEADERS }, body: { error: { code: e.code, message: e.message, details: e.details, requestId } } };
}

/**
 * The one 404 (API-CONTRACT §2 "조회 경로의 404"): unknown and out-of-scope ids/slugs must be indistinguishable —
 * same status, same body except requestId, same header set. Always build it here; never add details.
 */
export const notFound = (): ApiError => new ApiError(404, 'NOT_FOUND', 'Not found.');
export const validation = (fields: Array<{ field: string; message: string }>): ApiError =>
  new ApiError(400, 'VALIDATION_FAILED', fields[0]?.message ?? 'Invalid request.', { fields });
export const invalid = (field: string, message: string): ApiError => validation([{ field, message }]);
export const unauthenticated = (): ApiError => new ApiError(401, 'UNAUTHENTICATED', 'Sign in to continue.');
export const roleRequired = (role: string): ApiError => new ApiError(403, 'ROLE_REQUIRED', `This action needs the ${role} role.`, { role });
export const versionConflict = (what: string, currentVersion?: number): ApiError =>
  new ApiError(409, 'VERSION_CONFLICT', `${what} was updated by someone else.`, currentVersion === undefined ? {} : { currentVersion });
export const invalidTransition = (message: string): ApiError => new ApiError(409, 'INVALID_TRANSITION', message);

export const header = (req: ApiRequest, name: string): string | undefined => {
  const n = name.toLowerCase();
  for (const [k, v] of Object.entries(req.headers ?? {})) if (k.toLowerCase() === n && v !== undefined && v !== '') return v;
  return undefined;
};

/** Query value with empty strings dropped (9-6). */
export const q = (req: ApiRequest, name: string): string | undefined => {
  const v = req.query?.[name];
  return v === undefined || v === '' ? undefined : v;
};

/** `If-Match: 7`, `"7"` or `W/"7"` → 7. Missing → 400 (required on every guarded write, security R-3). */
export function ifMatch(req: ApiRequest): number {
  const raw = header(req, 'if-match');
  if (raw === undefined) throw invalid('If-Match', 'If-Match header with the version you saw is required.');
  const m = /^(?:W\/)?"?(\d{1,9})"?$/.exec(raw.trim());
  if (!m) throw invalid('If-Match', 'If-Match must be a version number.');
  return Number(m[1]);
}

export const etag = (...parts: string[]): string => `"${createHash('sha256').update(parts.join('\n')).digest('hex').slice(0, 32)}"`;

export const encodeCursor = (v: unknown): string => Buffer.from(JSON.stringify(v), 'utf8').toString('base64url');
export function decodeCursor<T>(raw: string | undefined, check: (v: unknown) => v is T): T | undefined {
  if (raw === undefined) return undefined;
  try {
    const v: unknown = JSON.parse(Buffer.from(raw, 'base64url').toString('utf8'));
    if (check(v)) return v;
  } catch { /* fall through */ }
  throw invalid('cursor', 'Invalid cursor.');
}

export function limitOf(req: ApiRequest, dflt = 50, max = 200): number {
  const raw = q(req, 'limit');
  if (raw === undefined) return dflt;
  if (!/^\d{1,4}$/.test(raw) || Number(raw) < 1) throw invalid('limit', 'limit must be a positive number.');
  return Math.min(max, Number(raw));
}

export const isRecord = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);
